-- 004: wachtwoord herstellen per e-mail en sessies kunnen intrekken.

BEGIN;

-- Hoort bij elke sessiecookie; ophogen maakt alle bestaande sessies ongeldig
-- (gebeurt na het herstellen van een wachtwoord).
ALTER TABLE "GEBRUIKER"
    ADD COLUMN IF NOT EXISTS sessie_versie INTEGER NOT NULL DEFAULT 0;

-- Eenmalige herstellinks. Alleen de SHA-256-hash van het token wordt opgeslagen.
CREATE TABLE IF NOT EXISTS "WACHTWOORD_HERSTEL" (
    herstel_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gebruiker_id INTEGER NOT NULL REFERENCES "GEBRUIKER"(gebruiker_id) ON DELETE CASCADE,
    token_hash CHAR(64) NOT NULL UNIQUE,
    aangemaakt_op TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    verloopt_op TIMESTAMPTZ NOT NULL,
    gebruikt_op TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS "idx_wachtwoord_herstel_gebruiker"
    ON "WACHTWOORD_HERSTEL" (gebruiker_id);

COMMIT;
